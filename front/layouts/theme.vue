<script setup>
const style = ref("light");
const color = ref("");
const reverseColor = ref("");

function changeTheme(newStyle = "light") {
  localStorage.setItem("theme", newStyle);
  setTheme();
}

function setTheme() {
  style.value = localStorage.getItem("theme") || "light";
  if (style.value === "dark") {
    document.documentElement.setAttribute("data-theme", "dark");
    color.value = "#00a9ed";
    reverseColor.value = "#d1d1d1";
  } else {
    document.documentElement.removeAttribute("data-theme");
    reverseColor.value = "#00a9ed";
    color.value = "#d1d1d1";
  }
}

onMounted(() => {
  setTheme();
});
</script>

